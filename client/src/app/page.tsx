/* FastAPI 動作確認*/

type Profile = {
  id: number;
  name: string;
  bio: string;
  image_id: number | null;
};

type Skill = {
  id: number;
  name: string;
};

type Work = {
  id: number;
  title: string;
  description: string;
}

export default async function Home() {
  const profileResponse = await fetch(`${process.env.FASTAPI_URL}/profile`);
  const profile: Profile = await profileResponse.json();

  const skillsResponse = await fetch(`${process.env.FASTAPI_URL}/skills`);
  const skills: Skill[] = await skillsResponse.json();

  const worksResponse = await fetch(`${process.env.FASTAPI_URL}/works`);
  const works: Work[] = await worksResponse.json();

  return (
    <main>
      <h1>{profile.name}</h1>
      <p>{profile.bio}</p>
      <ul>
        <li>
          {skills.map((skill) => (
            <li key={skill.id}>{skill.name}</li>
          ))}
        </li>
      </ul>
      <section>
        <h2>Works</h2>

        {works.map((work) => (
          <div key={work.id}>
            <h3>{work.title}</h3>
            <p>{work.description}</p>
          </div>
        ))}
      </section>
      {profile.image_id && (
        <img
          src={`${process.env.FASTAPI_URL}/images/${profile.image_id}`}
          alt={profile.name}
          width={200}
        />
      )}

    </main>
  );
}

